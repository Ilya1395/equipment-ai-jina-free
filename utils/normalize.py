def normalize_unit(unit: str) -> str:
    if not unit:
        return ""
    key = unit.strip().replace(" ", "").lower()
    key2 = unit.strip().lower()
    return UNIT_MAP.get(key, UNIT_MAP.get(key2, unit.strip()))


def normalize_characteristic(name: str) -> str:
    if not name:
        return ""
    clean = re.sub(r"\s+", " ", name).strip(" :-–—\t\n").lower()
    if clean in CHAR_MAP:
        return CHAR_MAP[clean]
    return clean[:1].upper() + clean[1:]


def split_value_unit(raw_value: str) -> Tuple[str, str]:
    raw_value = (raw_value or "").strip()
    match = re.match(r"^([<>≤≥~≈±\-+]?\s*\d+[\d\s.,/\-]*)\s*([а-яА-Яa-zA-Z°%³3/\.]+.*)?$", raw_value)
    if not match:
        return raw_value, ""
    value = match.group(1).replace(" ", "").replace(",", ".").strip()
    unit = normalize_unit((match.group(2) or "").strip())
    return value, unit
